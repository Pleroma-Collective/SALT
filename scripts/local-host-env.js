'use strict';
/**
 * Build the environment for running the dashboard on the HOST (not in docker)
 * against the already-running local postgres (127.0.0.1:55432, the host-mapped
 * port of the local debug postgres). Reads .env.local for the generated
 * secrets, then applies the host overrides. Persists TEST_ADMIN_TOKEN to
 * .env.local on first use so the local test-login token is stable across runs.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..'); // scripts/ lives directly under the repo root
const ENV_LOCAL = path.join(ROOT, '.env.local');

function readEnvLocal() {
  const out = {};
  if (!fs.existsSync(ENV_LOCAL)) return out;
  for (const raw of fs.readFileSync(ENV_LOCAL, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const m = line.match(/^([A-Za-z0-9_]+)=\s?(.*)$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

/**
 * Return a stable TEST_ADMIN_TOKEN, generating + persisting it to .env.local if
 * absent. Kept out of git (via .env.local's gitignore) — never set in prod.
 */
function ensureTestToken() {
  const existing = readEnvLocal();
  if (existing.TEST_ADMIN_TOKEN && existing.TEST_ADMIN_TOKEN.length >= 16) {
    return existing.TEST_ADMIN_TOKEN;
  }
  const token = crypto.randomBytes(24).toString('base64url');
  let lines = [];
  if (fs.existsSync(ENV_LOCAL)) lines = fs.readFileSync(ENV_LOCAL, 'utf8').split(/\r?\n/);
  lines = lines.filter((l) => l.trim() !== '' || !/^TEST_ADMIN_TOKEN=/.test(l.trim()));
  lines = lines.filter((l) => !l.trim().startsWith('TEST_ADMIN_TOKEN='));
  lines.push('# Local-testing backdoor token (never set in prod). Generated by scripts/local-host-env.js.');
  lines.push(`TEST_ADMIN_TOKEN=${token}`);
  fs.writeFileSync(ENV_LOCAL, lines.join('\n') + '\n', { mode: 0o600 });
  return token;
}

function localHostEnv() {
  const base = readEnvLocal();
  const env = { ...process.env, ...base };
  // Point at the host-mapped local postgres, not the in-container host name.
  env.POSTGRES_HOST = '127.0.0.1';
  env.POSTGRES_PORT = '55432';
  env.POSTGRES_DB = base.POSTGRES_DB || 'dayz-dashboard';
  env.POSTGRES_USER = base.POSTGRES_USER || 'dayz-dashboard';
  env.POSTGRES_SSL = 'false';
  env.DEPLOYMENT_MODE = 'local';
  env.NODE_ENV = 'development';
  env.SESSION_SECURE_COOKIE = 'false';
  env.RATE_LIMIT_ENABLED = 'false';
  // 'localhost' (not 127.0.0.1): this host resolves localhost to ::1 (IPv6),
  // and the Discord OAuth callback + browser session cookie are scoped to the
  // 'localhost' host. Binding 127.0.0.1 (IPv4 only) makes the browser unable
  // to reach the server, and the login callback can't complete.
  env.LISTEN_HOST = 'localhost';
  env.LOCAL_CONTAINER_RUNTIME = 'false';
  env.PORT = process.env.PORT || base.PORT || '3000';
  env.TEST_ADMIN_TOKEN = ensureTestToken();
  return env;
}

module.exports = { localHostEnv, readEnvLocal, ensureTestToken, ROOT, ENV_LOCAL };
